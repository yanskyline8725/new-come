#include <stdio.h>      // 基本输入输出函数（printf、文件操作等）
#include <errno.h>      // 用于获取错误原因
#include <string.h>     // 用于处理字符串的函数

// 程序入口，所有C程序都从main函数开始执行
int main() {
    // 定义文件指针，初始化为NULL（空），用于操作文件
    FILE *fptr = NULL;
    
    // 要读取的文件路径（这里尝试两种最常见的写法）
    // 注意：把下面的路径改成你实际的文件路径
    char *filePath1 = "E:/code_try/filename.txt";  // 带txt扩展名
    char *filePath2 = "E:/code_try/filename";      // 不带txt扩展名
    
    // 用于存储从文件中读取的内容，100表示最多存100个字符
    char readBuffer[100];
    
    // 用于记录读取的行数，方便查看
    int lineNum = 1;

    // 显示程序开始信息
    printf("=== 简单文件读取工具 ===\n");
    printf("准备读取文件...\n");

    // 第一步：尝试打开文件（先试带txt的路径）
    fptr = fopen(filePath1, "r");  // "r"表示只读模式打开
    
    // 如果打开失败（指针为空），再试不带txt的路径
    if (fptr == NULL) {
        printf("尝试打开 %s 失败，再试另一个路径...\n", filePath1);
        fptr = fopen(filePath2, "r");
    }

    // 检查文件是否成功打开（这是最关键的一步）
    if (fptr == NULL) {
        printf("❌ 无法打开文件！\n");
        printf("错误原因：%s\n", strerror(errno));  // 显示具体错误
        printf("请检查：\n");
        printf("1. 路径中的E盘是否正确\n");
        printf("2. 文件夹是否叫code_try\n");
        printf("3. 文件名是否正确（有没有txt后缀）\n");
        return 1;  // 打开失败，程序结束
    }

    // 第二步：文件打开成功，开始读取内容
    printf("✅ 文件打开成功！内容如下：\n");
    printf("-------------------------\n");

    // 循环读取文件内容，直到读完
    // fgets：从文件中读取一行内容到readBuffer，最多读100个字符
    while (fgets(readBuffer, 100, fptr) != NULL) {
        // 打印行号和读取到的内容
        printf("第%d行: %s", lineNum, readBuffer);
        lineNum++;  // 行号加1
    }

    // 第三步：读取完成，关闭文件（必须做，否则可能丢失数据）
    fclose(fptr);
    fptr = NULL;  // 清空指针，避免错误

    // 显示结束信息
    printf("-------------------------\n");
    printf("✅ 文件读取完毕，共%d行\n", lineNum - 1);
    printf("程序结束\n");

    return 0;
}
