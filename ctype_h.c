/*C 语言 ctype 函数
<ctype.h> 头文件提供了许多用于分类和修改字符的函数。

函数	描述
isalnum()	检查字符是否为字母或数字。
isalpha()	检查字符是否为字母。
isblank()	检查字符是否为空格或制表符。
iscntrl()	检查字符是否为控制字符。
isdigit()	检查字符是否为十进制数字。
isgraph()	检查字符是否有图形表示（即非空白且非控制字符）。
islower()	检查字符是否为小写字母。
isprint()	检查字符是否为可打印字符。
ispunct()	检查字符是否为标点符号。
isspace()	检查字符是否为空白字符（包括空格、制表符、换行符等）。
isupper()	检查字符是否为大写字母。
isxdigit()	检查字符是否为十六进制数字。
tolower()	返回字符的小写版本。
toupper()	返回字符的大写版本。
这些函数使你能够在 C 语言中执行各种字符分类和转换操作。
*/