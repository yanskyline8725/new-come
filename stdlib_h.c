/*C 标准库函数
<stdlib.h> 头文件（标准库）提供了多种常用的函数。

函数	描述
abs()	返回整数的绝对值（正数）。
atof()	从数字的字符串表示形式返回 double 值。
atoi()	从整数的字符串表示形式返回 int 值。
atol()	从整数的字符串表示形式返回 long int 值。
atoll()	从整数的字符串表示形式返回 long long int 值。
calloc()	分配动态内存并用零填充。
div()	返回整数除法的商和余数。
exit()	结束程序。
free()	释放动态内存。
malloc()	分配动态内存。
qsort()	对数组的内容进行排序。
rand()	生成随机整数。
realloc()	重新分配动态内存。
srand()	初始化随机数生成器。
strtod()	将字符串转换为 double 值。
strtof()	将字符串转换为 float 值。
strtol()	将字符串转换为 long int 值。
strtoll()	将字符串转换为 long long int 值。
strtoul()	将字符串转换为 unsigned long int 值。
strtoull()	将字符串转换为 unsigned long long int 值。
这些函数使你能够在 C 语言中执行各种常见任务，包括内存管理、字符串转换和数学计算。
*/